const UUID = /[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/i;
const ULID = /^[0-9A-HJKMNP-TV-Z]{26}$/;

const GENERATED: RegExp[] = [
  /^css-[a-z0-9]+(-[a-z0-9-]+)?$/i, // emotion: css-1x9f2k, css-1x9f2k-Button
  /^sc-/, // styled-components
  /^jss\d+/i, // JSS
  /-jss\d+$/i,
  /^makeStyles-/, // MUI v4
  /^:r[0-9a-z]*:$/i, // React useId (18)
  /^«r[0-9a-z]*»$/i, // React useId (19)
  /^_r_[0-9a-z]+_$/i, // React useId (19.1+)
  /^ember\d+$/i,
  /^ext-(comp|gen|element)-?\d+/i, // ExtJS
  /^yui_/i,
  /^ng-tns-/, // Angular animations
  /^_ngcontent-/,
  /^svelte-[a-z0-9]+$/i,
  /^astro-[a-z0-9]+$/i,
  /^data-v-[a-f0-9]+$/i, // Vue scoped
  /__[A-Za-z0-9_-]{5,}$/, // CSS modules: Button_primary__3xK9z
  /\d{4,}/, // long digit runs
  UUID,
  ULID,
  /^[0-9a-f]{8,}$/i, // bare hex hashes
  /^[_-]?[a-z]{0,3}\d{2,}$/i, // short prefix + number: a12, _31, x99
  // Component libraries that number ids per page load (D63): mat-select-10, cdk-overlay-3,
  // headlessui-menu-button-3, downshift-0-input, react-select-2-input, rc-tabs-0-tab-1.
  // Not Material typography classes (mat-display-1, mat-headline-2).
  /^(?!mat-(display|headline)-)(mat|mdc|cdk|headlessui|downshift|react-select|react-aria|rc|mui|chakra|reach)-([a-z-]*-)?\d+(-|$)/i,
];

const STATE_CLASS =
  /^(is-|has-|was-)|^(active|focus(ed)?|hover(ed)?|selected|open(ed)?|closed|disabled|checked|expanded|collapsed|visible|hidden|show|shown|current|loading|pressed)$/i;

/** camelCase / PascalCase words: "addToCart" -> add, To, Cart; "getHTMLElement" -> get, HTML, Element. */
const CAMEL_WORD = /[A-Z]{2,}(?![a-z])|[A-Z]?[a-z]+|[A-Z]|\d+/g;

/**
 * True when a segment reads as camelCase words. Hash fragments split into short chunks
 * ("bdVaJa" -> bd, Va, Ja); words do not. So: no two-letter chunk without a vowel ("bd", "Kq",
 * "Hs"), and at least one word of 3+ letters.
 * "addToCart", "goToTop", "submitBtnPrimary" are words; "bdVaJa", "xKq3Fz", "VaJaBo" are not.
 */
function isCamelWords(seg: string): boolean {
  let longWord = false;
  for (const w of seg.match(CAMEL_WORD) ?? []) {
    if (w.length >= 3 && !/^\d+$/.test(w)) longWord = true; // words, "Btn", acronyms
    else if (w.length === 2 && /^[a-z]+$/i.test(w) && !/[aeiouy]/i.test(w) && !/^[A-Z]{2}$/.test(w)) return false; // "bd", "Kq"
  }
  return longWord;
}

/** True when one segment of a token looks random (a hash) rather than a word. */
function looksRandomSegment(seg: string): boolean {
  if (seg.length < 5) return false;
  const digits = (seg.match(/\d/g) ?? []).length;
  const letters = (seg.match(/[a-z]/gi) ?? []).length;
  if (digits >= 2 && letters >= 1) return true;
  // case or letter/digit transitions typical of hashes: "xKq3Fz", "bdVaJa"
  let transitions = 0;
  for (let i = 1; i < seg.length; i++) {
    const a = seg[i - 1]!;
    const b = seg[i]!;
    const kind = (c: string) => (/\d/.test(c) ? 0 : c === c.toUpperCase() ? 1 : 2);
    if (kind(a) !== kind(b)) transitions++;
  }
  // Ordinary camelCase ids ("addToCart", "deleteRowButton") have as many transitions as a
  // hash; split them into words first and keep them when the words read as words.
  return transitions >= 4 && !isCamelWords(seg);
}

/** Ids, classes and attribute values that look generated by a framework or build tool. */
export function isGeneratedToken(token: string, extraPatterns: RegExp[] = []): boolean {
  const t = token.trim();
  if (!t) return true;
  if (GENERATED.some((re) => re.test(t))) return true;
  if (extraPatterns.some((re) => re.test(t))) return true;
  const segs = t.split(/[-_:.]+/).filter(Boolean);
  if (segs.some(looksRandomSegment)) return true;
  return hasHashSuffix(segs);
}

/**
 * Short build hashes split across the last one or two segments, as in CSS modules with
 * hyphenated hashes: `prc-Button-ButtonBase-9n-Xk`, `prc-components-UnderlineItem-7fP-n`.
 * A tail of 2 to 8 characters that mixes a digit with an upper-case letter is a hash;
 * `col-md-6` or `grid-cols-12` (no upper case) are not.
 */
function hasHashSuffix(segs: string[]): boolean {
  if (segs.length < 3) return false;
  const isHash = (tail: string) => tail.length >= 2 && tail.length <= 8 && /\d/.test(tail) && /[A-Z]/.test(tail) && /^[A-Za-z0-9]+$/.test(tail);
  const last = segs[segs.length - 1]!;
  const two = segs[segs.length - 2]! + last;
  return (segs[segs.length - 2]!.length <= 5 && last.length <= 5 && isHash(two)) || (last.length >= 3 && isHash(last));
}

/** Classes that describe a transient UI state; never part of an identity. */
export function isStateClass(cls: string): boolean {
  return STATE_CLASS.test(cls);
}

const MONTHS = '(jan|feb|mar|apr|may|jun|jul|aug|sep|sept|oct|nov|dec)[a-z]*\\.?';
const DATA_LIKE: RegExp[] = [
  /[^\s@]+@[^\s@]+\.[^\s@]+/, // email
  /(?:\+?\d[\d\s().-]{6,}\d)/, // phone-ish (checked for digit count below)
  /[$€£¥₹₩₽¢]\s?\d|\d\s?[$€£¥₹₩₽¢]|\b(usd|eur|gbp|jpy)\s?\d|\d\s?(usd|eur|gbp|jpy)\b/i, // money
  /\b\d{1,3}(?:[,.\s]\d{3})+(?:[.,]\d+)?\b/, // 1,234 / 1.234,56
  /\b\d+[.,]\d{2}\b/, // 12.50
  /\b\d{1,4}[/.-]\d{1,2}[/.-]\d{1,4}\b/, // dates
  new RegExp(`\\b${MONTHS}\\s+\\d{1,2}\\b|\\b\\d{1,2}\\s+${MONTHS}`, 'i'), // Nov 4 / 4 Nov
  /\b\d{1,2}:\d{2}\b/, // times
  /\d{4,}/, // long numbers, ids, years
  /#\d{2,}/, // #123
  /\b(?=[A-Z0-9-]*\d)(?=[A-Z0-9-]*[A-Z])[A-Z0-9]+(?:-[A-Z0-9]+)+\b/, // INV-2039, AB-12
  /\b(?=\w*\d)(?=\w*[a-z])\w{8,}\b/i, // long mixed tokens: a8f3kl92x
  UUID,
  /\b\d+(\.\d+)?\s?%/, // percentages
];

export const MAX_TEXT = 80;

/**
 * Text that looks like data rather than a UI label: emails, phone numbers, amounts, dates,
 * codes, or anything longer than 80 characters. Applied to own text, accessible names,
 * option labels, link paths and page titles.
 */
export function isDataLike(text: string): boolean {
  const t = text.trim();
  if (t.length > MAX_TEXT) return true;
  for (const re of DATA_LIKE) {
    const m = re.exec(t);
    if (!m) continue;
    if (re === DATA_LIKE[1]) {
      if ((m[0].match(/\d/g) ?? []).length >= 7) return true;
      continue;
    }
    return true;
  }
  return false;
}

/** Returns the text if it is a safe, short UI label, otherwise undefined. */
export function safeLabel(text: string | null | undefined): string | undefined {
  const t = (text ?? '').replace(/\s+/g, ' ').trim();
  if (!t || isDataLike(t)) return undefined;
  return t;
}
